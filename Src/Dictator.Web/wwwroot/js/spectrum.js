    function render(buffer, borderColor) {
        lastBuffer = buffer;
        lastBorderColor = borderColor;
        renderInternal(buffer, borderColor);
    }

    function renderInternal(buffer, borderColor) {
        if (!ctx || !imgData) return;

        const data = imgData.data;
        const borderRgb = PALETTE[borderColor & 0x0F] || PALETTE[0];

        // Fill border & background first
        for (let i = 0; i < WIDTH * HEIGHT * 4; i += 4) {
            data[i] = borderRgb[0];
            data[i + 1] = borderRgb[1];
            data[i + 2] = borderRgb[2];
            data[i + 3] = 255;
        }

        // Draw 32x24 cells into active 256x192 region
        for (let r = 0; r < ROWS; r++) {
            for (let c = 0; c < COLS; c++) {
                const packed = buffer[r * COLS + c];
                const charCode = packed & 0xFFFF;
                let bgIdx = (packed >> 16) & 0x0F;
                let fgIdx = (packed >> 20) & 0x0F;
                const isFlash = ((packed >> 24) & 0x01) === 1;

                if (isFlash && flashInverted) {
                    const tmp = bgIdx;
                    bgIdx = fgIdx;
                    fgIdx = tmp;
                }

                const bgRgb = PALETTE[bgIdx];
                const fgRgb = PALETTE[fgIdx];
                const glyph = ZX_FONT[charCode] || ZX_FONT[32];

                const baseX = BORDER_PX + c * 8;
                const baseY = BORDER_PX + r * 8;

                for (let py = 0; py < 8; py++) {
                    const rowBits = glyph[py];
                    let pixelOffset = ((baseY + py) * WIDTH + baseX) * 4;

                    for (let bit = 7; bit >= 0; bit--) {
                        const isInk = ((rowBits >> bit) & 1) === 1;
                        const rgb = isInk ? fgRgb : bgRgb;
                        data[pixelOffset] = rgb[0];
                        data[pixelOffset + 1] = rgb[1];
                        data[pixelOffset + 2] = rgb[2];
                        data[pixelOffset + 3] = 255;
                        pixelOffset += 4;
                    }
                }
            }
        }

        ctx.putImageData(imgData, 0, 0);
    }

    function setSoundEnabled(enabled) {
        soundEnabled = enabled;
    }

    function beep(freq = 880, durationMs = 45) {
        if (!soundEnabled) return;
        try {
            if (!audioCtx) {
                audioCtx = new (window.AudioContext || window.webkitAudioContext)();
            }
            if (audioCtx.state === 'suspended') {
                audioCtx.resume();
            }
            const osc = audioCtx.createOscillator();
            const gain = audioCtx.createGain();
            osc.type = 'square';
            osc.frequency.setValueAtTime(freq, audioCtx.currentTime);
            gain.gain.setValueAtTime(0.06, audioCtx.currentTime);
            gain.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + durationMs / 1000);
            osc.connect(gain);
            gain.connect(audioCtx.destination);
            osc.start();
            osc.stop(audioCtx.currentTime + durationMs / 1000);
        } catch {
            // Ignore audio errors if browser blocks autoplay
        }
    }

